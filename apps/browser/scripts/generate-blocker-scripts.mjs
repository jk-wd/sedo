#!/usr/bin/env node
// Fill each dark-patterns/<pattern>/<site>/block.template.js from selectors.json.
// Writes block.js, block_script.inc, and selectors.inc next to the template.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const patternsRoot = path.join(root, 'src/chrome/browser/sedo/dark-patterns');

function cppString(value) {
  const escaped = value
    .replaceAll('\\', '\\\\')
    .replaceAll('"', '\\"')
    .replaceAll('\n', '\\n');
  return `"${escaped}"`;
}

function jsArray(values) {
  return `[${values.map((value) => JSON.stringify(value)).join(', ')}]`;
}

function assertStringList(file, name, values) {
  if (!Array.isArray(values) || values.some((value) => typeof value !== 'string' || value.length === 0)) {
    throw new Error(`${file}: ${name} must be a list of non-empty strings`);
  }
}

function walk(dir, found) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === 'proof' || entry.name === 'node_modules') continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      walk(full, found);
    } else if (entry.name === 'selectors.json') {
      found.push(full);
    }
  }
}

function generate(selectorsPath) {
  const siteDir = path.dirname(selectorsPath);
  const site = path.basename(siteDir);
  const pattern = path.basename(path.dirname(siteDir));
  const data = JSON.parse(fs.readFileSync(selectorsPath, 'utf8'));
  if (data.pattern !== pattern || data.site !== site) {
    throw new Error(
      `${selectorsPath}: pattern/site must match the folder ${pattern}/${site}`,
    );
  }
  if (!data.arrays && !data.strings && !data.numbers) {
    throw new Error(`${selectorsPath}: expected arrays, strings, or numbers`);
  }

  const replacements = {
    pattern: JSON.stringify(pattern),
    site: JSON.stringify(site),
  };
  const inc = [
    '// Generated by scripts/generate-blocker-scripts.mjs. Do not edit.',
    `// Pattern: ${pattern}. Site: ${site}.`,
    '',
  ];
  for (const [name, values] of Object.entries(data.arrays ?? {})) {
    assertStringList(selectorsPath, name, values);
    if (Object.hasOwn(replacements, name)) {
      throw new Error(`${selectorsPath}: duplicate name ${name}`);
    }
    replacements[name] = jsArray(values);
    const lines = values.map((value) => `    ${cppString(value)},`);
    inc.push(`[[maybe_unused]] constexpr std::string_view ${name}[] = {`, ...lines, '};', '');
  }
  for (const [name, value] of Object.entries(data.strings ?? {})) {
    if (typeof value !== 'string' || value.length === 0) {
      throw new Error(`${selectorsPath}: ${name} must be a non-empty string`);
    }
    if (Object.hasOwn(replacements, name)) {
      throw new Error(`${selectorsPath}: duplicate name ${name}`);
    }
    replacements[name] = JSON.stringify(value);
    inc.push(`[[maybe_unused]] constexpr std::string_view ${name} =`, `    ${cppString(value)};`, '');
  }
  for (const [name, value] of Object.entries(data.numbers ?? {})) {
    if (typeof value !== 'number' || !Number.isFinite(value)) {
      throw new Error(`${selectorsPath}: ${name} must be a finite number`);
    }
    if (Object.hasOwn(replacements, name)) {
      throw new Error(`${selectorsPath}: duplicate name ${name}`);
    }
    replacements[name] = String(value);
    inc.push(`[[maybe_unused]] constexpr double ${name} = ${Number.isInteger(value) ? `${value}.0` : value};`, '');
  }
  // A font file next to selectors.json reaches the page script as base64. It
  // is not written to selectors.inc.
  for (const [name, file] of Object.entries(data.fonts ?? {})) {
    const fontPath = path.join(siteDir, file);
    if (typeof file !== 'string' || path.dirname(fontPath) !== siteDir || !fs.existsSync(fontPath)) {
      throw new Error(`${selectorsPath}: ${name} must name a font file in this folder`);
    }
    if (Object.hasOwn(replacements, name)) {
      throw new Error(`${selectorsPath}: duplicate name ${name}`);
    }
    replacements[name] = JSON.stringify(fs.readFileSync(fontPath).toString('base64'));
  }

  const templatePath = path.join(siteDir, 'block.template.js');
  const template = fs.readFileSync(templatePath, 'utf8');
  const used = new Set();
  const body = template.replace(/%%([A-Za-z0-9_]+)%%/g, (_match, name) => {
    if (!Object.hasOwn(replacements, name)) {
      throw new Error(`${templatePath}: missing value for %%${name}%%`);
    }
    used.add(name);
    return replacements[name];
  });
  if (body.includes('%%')) {
    throw new Error(`${templatePath}: an unreplaced %% token remains`);
  }
  for (const name of Object.keys(replacements)) {
    if (!used.has(name)) {
      throw new Error(`${templatePath}: %%${name}%% is missing from the template`);
    }
  }
  if (body.includes(')SEDOJS"')) {
    throw new Error(`${templatePath}: script contains the raw-string terminator`);
  }

  const banner = [
    '// Generated by scripts/generate-blocker-scripts.mjs from selectors.json and block.template.js.',
    `// Pattern: ${pattern}. Site: ${site}.`,
    '',
  ].join('\n');
  const js = `${banner}${body.endsWith('\n') ? body : `${body}\n`}`;
  fs.writeFileSync(path.join(siteDir, 'block.js'), js);
  fs.writeFileSync(path.join(siteDir, 'block_script.inc'), `R"SEDOJS(${js})SEDOJS"\n`);
  fs.writeFileSync(path.join(siteDir, 'selectors.inc'), `${inc.join('\n')}\n`);
  console.log(`Generated ${pattern}/${site}`);
}

if (!fs.existsSync(patternsRoot)) {
  console.error(`No dark-pattern blockers at ${patternsRoot}`);
  process.exit(1);
}
const found = [];
walk(patternsRoot, found);
if (found.length === 0) {
  console.error(`No selectors.json under ${patternsRoot}`);
  process.exit(1);
}
for (const selectorsPath of found) {
  generate(selectorsPath);
}
